def strip_note(label):
    """去掉括号备注，如 '丹青彩绘（重装画）' -> '丹青彩绘'"""
    label = label.strip()
    # 去掉括号内容
    label = re.sub(r'[（(][^）)]*[）)]', '', label).strip()
    # 去掉尾部空格和逗号
    label = label.rstrip('，、, ')
    return label

def split_multi(label, sep_pattern='[、,，;；]'):
    """按分隔符拆分复合标签"""
    parts = re.split(sep_pattern, label)
    return [p.strip() for p in parts if p.strip()]

def get_practice_hierarchy(label):
    """对单个实践行为标签，返回 (一级, 二级, 三级, 四级) 中文"""
    label = label.strip()
    if not label or label.upper() == 'NULL':
        return ('信息不详', '信息不详', '信息不详', '信息不详')
    
    # 尝试直接匹配
    result = _PRACTICE_LABEL_TO_CODE.get(label)
    
    if result is None:
        # 尝试去掉括号备注后再匹配
        stripped = strip_note(label)
        if stripped != label:
            result = _PRACTICE_LABEL_TO_CODE.get(stripped)
    
    if result is None:
        # 再试关键词匹配（取最长的匹配前缀）
        best = None
        best_len = 0
        for kw, code_info in _PRACTICE_LABEL_TO_CODE.items():
            if kw in label and len(kw) > best_len:
                best = (kw, code_info)
                best_len = len(kw)
        if best:
            result = best[1]
    
    if result is None:
        # fallback
        return ('信息不详', '信息不详', '信息不详', '信息不详')
    
    code, level = result  # code like 'A-01-01', level = 3
    
    # 检查是否有层级覆盖
    level_override = _PRACTICE_LABEL_LEVEL_OVERRIDE.get(label) or _PRACTICE_LABEL_LEVEL_OVERRIDE.get(strip_note(label))
    if level_override:
        level = level_override
    
    # 从编码反向查中文
    # 一级
    l1_code = code.split('-')[0]
    l1_name = _PRACTICE_LEVEL1.get(l1_code, l1_code)
    
    # 二级（取前两段）
    parts = code.split('-')
    if len(parts) >= 2:
        l2_code = f'{parts[0]}-{parts[1]}'
        l2_info = _PRACTICE_LEVEL2.get(l2_code)
        l2_name = l2_info[1] if l2_info else l2_code
    else:
        l2_name = ''
    
    # 三级（取前三段）
    if len(parts) >= 3:
        l3_code = f'{parts[0]}-{parts[1]}-{parts[2]}'
        l3_info = _PRACTICE_LEVEL3.get(l3_code)
        l3_name = l3_info[1] if l3_info else l3_code
    else:
        l3_name = ''
    
    # 四级（取全部四段）
    if len(parts) >= 4:
        l4_code = code  # full code
        l4_info = _PRACTICE_LEVEL4.get(l4_code)
        l4_name = l4_info[1] if l4_info else l4_code
    else:
        # 如果是三级且无四级，使用三级名作为四级名
        if level >= 3 and l3_name:
            l4_name = l3_name
        else:
            l4_name = ''
    
    # 如果标签自身是四级，覆盖 l4_name
    if level == 4:
        # 标签可能是关键词，直接用它
        l4_name = label
    
    # 调整: 如果是三级但三级名可用，三级=三级名，四级=三级名
    if level == 3:
        if l3_name and not l4_name:
            l4_name = l3_name
    
    # 如果是二级
    if level == 2:
        if l2_name and not l3_name:
            l3_name = l2_name
            l4_name = l2_name
    
    # 如果是一级
    if level == 1:
        l2_name = l1_name
        l3_name = l1_name
        l4_name = l1_name
    
    # 确保不为空
    l1_name = l1_name or l1_code
    l2_name = l2_name or l1_name
    l3_name = l3_name or l2_name
    l4_name = l4_name or l3_name
    
    return (l1_name, l2_name, l3_name, l4_name)


