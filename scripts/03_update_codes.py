def merge_hierarchies(hier_list):
    """合并多个层级结果（用于复合标签如 '发心镌造、丹青彩绘'）
    返回 (一级, 二级, 三级, 四级) 用分号分隔
    """
    if not hier_list:
        return ('', '', '', '')
    
    l1s, l2s, l3s, l4s = [], [], [], []
    for h in hier_list:
        l1s.append(h[0])
        l2s.append(h[1])
        l3s.append(h[2])
        l4s.append(h[3])
    
    return ('；'.join(l1s), '；'.join(l2s), '；'.join(l3s), '；'.join(l4s))


def reunite(val, sep_pattern='[、,，]'):
    """对于实践行为的复合标签, 分割、映射、再合并"""
    if not val or val.strip().upper() == 'NULL':
        return ('信息不详', '信息不详', '信息不详', '信息不详')
    
    val = val.strip()
    parts = re.split(sep_pattern, val)
    parts = [p.strip() for p in parts if p.strip()]
    
    if not parts:
        return ('信息不详', '信息不详', '信息不详', '信息不详')
    
    hierarchies = []
    for p in parts:
        h = get_practice_hierarchy(p)
        hierarchies.append(h)
    
    return merge_hierarchies(hierarchies)


